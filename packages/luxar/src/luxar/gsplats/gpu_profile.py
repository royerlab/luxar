def get_gpu_summary(
    gpu_name: Optional[str] = None,
    gpu_mem: Optional[float] = None,
    path: Path = PROFILE_PATH,
) -> Optional[Dict[str, Any]]:
    """Get the summary for a GPU.

    Args:
        gpu_name: Exact GPU name. If ``None``, tries auto-detection via
            ``torch.cuda``, then falls back to the only profiled GPU.
        gpu_mem: If set and gpu_name is None, pick the profile whose
            ``total_memory_gb`` is closest to this value.
        path: Profile YAML path.

    Returns:
        Summary dict or ``None`` if no matching profile exists.
    """
    profiles = load_profiles(path)
    gpus = profiles.get("gpus", {})

    if not gpus:
        return None

    if gpu_name is not None:
        entry = gpus.get(gpu_name)
        if entry is None:
            return None
        summary: Dict[str, Any] = entry["summary"]
        return summary

    # Auto-detect from current CUDA device
    detected_name = _detect_gpu_name()
    if detected_name and detected_name in gpus:
        detected_summary: Dict[str, Any] = gpus[detected_name]["summary"]
        return detected_summary

    # Match by GPU memory
    if gpu_mem is not None:
        best_name = None
        best_diff = float("inf")
        for name, entry in gpus.items():
            mem = entry.get("info", {}).get("total_memory_gb", 0)
            diff = abs(mem - gpu_mem)
            if diff < best_diff:
                best_diff = diff
                best_name = name
        if best_name:
            mem_summary: Dict[str, Any] = gpus[best_name]["summary"]
            return mem_summary

    # If only one GPU profiled, use it
    if len(gpus) == 1:
        single_summary: Dict[str, Any] = next(iter(gpus.values()))["summary"]
        return single_summary

    # Multiple profiles but no GPU available for auto-detection (e.g. login
    # node) — pick the one with the least memory (conservative).
    if gpus:
        conservative_name = min(
            gpus,
            key=lambda n: gpus[n].get("info", {}).get("total_memory_gb", 0),
        )
        return dict(gpus[conservative_name]["summary"])

    return None


def get_gpu_throughput_table(
    gpu_name: Optional[str] = None,
    path: Path = PROFILE_PATH,
) -> Optional[List[Dict[str, Any]]]:
    """Get the averaged 3D throughput table for a GPU.

    Returns list of throughput entries sorted by voxel count, or None.
    """
    profiles = load_profiles(path)
    gpus = profiles.get("gpus", {})

    # Resolve GPU name
    name = gpu_name
    if name is None:
        name = _detect_gpu_name()
    if name is None and len(gpus) == 1:
        name = next(iter(gpus.keys()))
    if name is None or name not in gpus:
        return None

    summary = gpus[name].get("summary", {})
    table = summary.get("throughput_avg", {}).get("3d", [])
    # Sort by voxel count
    return sorted(table, key=lambda e: e.get("voxels", 0))


def list_profiled_gpus(path: Path = PROFILE_PATH) -> List[str]:
    """List all GPU names that have profiles."""
    profiles = load_profiles(path)
    return list(profiles.get("gpus", {}).keys())


# ---------------------------------------------------------------------------
# V1 migration
# ---------------------------------------------------------------------------


def migrate_v1_profile(
    old_path: Path,
    new_path: Path = PROFILE_PATH,
) -> bool:
    """Migrate old single-GPU profile (v1) to the new multi-GPU format.

    Reads the old YAML, wraps its data as a single run, writes to the new
    location. Renames the old file to ``.bak``.

    Returns:
        True if migration happened, False if old file not found or invalid.
    """
    if not old_path.exists():
        return False

    with open(old_path) as f:
        old_data = yaml.safe_load(f)

    if old_data is None or not isinstance(old_data, dict):
        return False

    gpu_info_raw = old_data.get("gpu", {})
    gpu_name = gpu_info_raw.get("name")
    if not gpu_name:
        return False

    # Build gpu_info (static hardware info)
    gpu_info = {
        k: v
        for k, v in gpu_info_raw.items()
        if k in ("total_memory_gb", "compute_capability", "sm_count")
    }

    # Build run_data (everything else)
    run_data: Dict[str, Any] = {
        "timestamp": old_data.get("timestamp", "unknown"),
        "cuda_version": gpu_info_raw.get("cuda_version", "unknown"),
        "pytorch_version": gpu_info_raw.get("pytorch_version", "unknown"),
        "free_memory_gb": gpu_info_raw.get("free_memory_gb", 0),
        "throughput": old_data.get("throughput", {}),
        "oom_boundaries": old_data.get("oom_boundaries", {}),
        "recommendations": old_data.get("recommendations", {}),
    }
    if "splat_sweep" in old_data:
        run_data["splat_sweep"] = old_data["splat_sweep"]

    # Build new structure
    profiles: Dict[str, Any] = {
        "schema_version": SCHEMA_VERSION,
        "gpus": {
            gpu_name: {
                "info": gpu_info,
                "runs": [run_data],
                "summary": recompute_summary([run_data]),
            }
        },
    }

    save_profiles(profiles, new_path)

    # Rename old file (safe even if .bak already exists)
    backup_path = old_path.with_suffix(".yaml.bak")
    try:
        old_path.rename(backup_path)
    except OSError:
        # .bak may already exist or rename failed — just delete old file
        try:
            old_path.unlink()
        except OSError:
            pass

    return True


# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------


def _detect_gpu_name() -> Optional[str]:
    """Detect current GPU name via torch.cuda, or None."""
    try:
        import torch as _torch
    except ImportError:
        return None

    try:
        if _torch.cuda.is_available():
            return _torch.cuda.get_device_properties(0).name
    except (RuntimeError, AssertionError):
        # CUDA initialization or driver errors
        pass
    return None
