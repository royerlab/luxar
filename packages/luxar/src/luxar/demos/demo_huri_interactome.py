def compute_communities(nodes: list[str], edges: pd.DataFrame) -> np.ndarray:
    """Louvain community assignment per node. Communities sorted by size desc."""
    import networkx as nx

    with asection("Detecting communities (Louvain)"):
        g = nx.Graph()
        g.add_nodes_from(nodes)
        g.add_edges_from(
            zip(edges["sym_a"].tolist(), edges["sym_b"].tolist(), strict=True)
        )
        partitions = nx.community.louvain_communities(g, seed=42)
        partitions = sorted(partitions, key=len, reverse=True)
        aprint(f"  {len(partitions)} communities detected")
        for i, p in enumerate(partitions[:5]):
            aprint(f"    #{i}: {len(p):,} nodes")
        if len(partitions) > 5:
            aprint(f"    ... + {len(partitions) - 5} smaller")

        idx = {s: i for i, s in enumerate(nodes)}
        comms = np.full(len(nodes), -1, dtype=np.int32)
        for comm_id, members in enumerate(partitions):
            for symbol in members:
                comms[idx[symbol]] = comm_id
    return comms


def load_corum_lookup(
    corum_path: Path | None,
) -> dict[frozenset, list[str]]:
    """Build {frozenset({symA, symB}) → [complex_name, ...]} for human pairs."""
    if corum_path is None or not corum_path.exists():
        return {}

    with asection("Loading CORUM complex memberships"):
        df = pd.read_csv(corum_path, sep="\t", low_memory=False, dtype=str)
        aprint(f"  {len(df):,} rows, {df.shape[1]} columns")

        # Column names vary mildly across CORUM releases
        def _find(cols_lower_contains: list[str]) -> str | None:
            for c in df.columns:
                cl = c.lower()
                if all(tok in cl for tok in cols_lower_contains):
                    return c
            return None

        name_col = _find(["complexname"])
        subunit_col = _find(["subunits", "gene name"])
        organism_col = _find(["organism"])
        if name_col is None or subunit_col is None:
            aprint(
                f"  ⚠ Could not find CORUM name/subunit columns "
                f"(have: {list(df.columns)[:8]}...); skipping"
            )
            return {}

        if organism_col is not None:
            organism = df[organism_col].fillna("").str.lower()
            df = df[organism.isin({"human", "homo sapiens", "mammalia, human"})]
            aprint(f"  {len(df):,} human complexes")

        pair_to_complexes: dict[frozenset, list[str]] = {}
        for row in df[[name_col, subunit_col]].itertuples(index=False):
            name, subunits = row
            if not isinstance(subunits, str) or not subunits.strip():
                continue
            for delim in (";", ",", "|"):
                if delim in subunits:
                    subs = [s.strip() for s in subunits.split(delim) if s.strip()]
                    break
            else:
                subs = [subunits.strip()]
            if len(subs) < 2:
                continue
            for i in range(len(subs)):
                for j in range(i + 1, len(subs)):
                    key = frozenset({subs[i], subs[j]})
                    pair_to_complexes.setdefault(key, []).append(str(name))

        aprint(f"  {len(pair_to_complexes):,} protein pairs in ≥1 CORUM complex")
    return pair_to_complexes


