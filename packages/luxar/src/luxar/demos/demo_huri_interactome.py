def _community_palette(n_comms: int) -> np.ndarray:
    """(n_comms, 3) float32 in [0,1]."""
    return (
        np.array(
            [get_categorical_color(i, n_comms) for i in range(n_comms)],
            dtype=np.float32,
        )
        / 255.0
    )


def build_node_points(
    nodes: list[str],
    node_df: pd.DataFrame,
    coords: np.ndarray,
    communities: np.ndarray,
    degrees: np.ndarray,
) -> tuple[
    np.ndarray,
    np.ndarray,
    np.ndarray,
    list[str],
    list[str],
    np.ndarray,
    np.ndarray,
    np.ndarray,
]:
    """Assemble Points attributes duplicated across both color views.

    Returns:
        positions (2N, 4), colors (2N, 3), radii (2N,), labels (2N,),
        chrom_categories, chrom_codes (N,), community_palette (K, 3),
        chrom_palette (C, 3)
    """
    n = len(nodes)

    # Community colors
    n_comms = int(communities.max()) + 1
    comm_palette = _community_palette(n_comms)
    comm_colors = comm_palette[communities]

    # Chromosome colors (deterministic category order: numeric then X/Y/MT/?)
    def _chrom_sort_key(c: str) -> tuple[int, str]:
        if c == "?":
            return (99, "")
        if c.isdigit():
            return (int(c), "")
        return (50, c)  # X, Y, MT before "?"

    chroms = node_df["chromosome"].tolist()
    chrom_cats = sorted(set(chroms), key=_chrom_sort_key)
    chrom_idx = {c: i for i, c in enumerate(chrom_cats)}
    chrom_codes = np.array([chrom_idx[c] for c in chroms], dtype=np.int32)
    chrom_palette = (
        np.array(
            [get_categorical_color(i, len(chrom_cats)) for i in range(len(chrom_cats))],
            dtype=np.float32,
        )
        / 255.0
    )
    chrom_colors = chrom_palette[chrom_codes]

    # Radii scale with log(degree) so hubs are visible
    log_deg = np.log1p(degrees.astype(np.float32))
    log_deg /= max(float(log_deg.max()), 1.0)
    radii_per_node = (0.06 + 0.18 * log_deg).astype(np.float32)

    # Positions for two views stacked
    n_verts_per_view = n
    pos_view0 = np.empty((n_verts_per_view, 4), dtype=np.float32)
    pos_view0[:, 0] = 0.0
    pos_view0[:, 1:] = coords
    pos_view1 = pos_view0.copy()
    pos_view1[:, 0] = 1.0
    positions = np.vstack([pos_view0, pos_view1])

    colors = np.vstack([comm_colors, chrom_colors])
    radii = np.concatenate([radii_per_node, radii_per_node])

    # Hover labels (one per vertex, replicated per view)
    per_node_labels = [
        f"{sym}\n[chr{ch} · deg {int(d)} · community {int(c)}]"
        for sym, ch, d, c in zip(nodes, chroms, degrees, communities, strict=True)
    ]
    labels = per_node_labels * 2

    return (
        positions,
        colors,
        radii,
        labels,
        chrom_cats,
        chrom_codes,
        comm_palette,
        chrom_palette,
    )


def build_edge_lines(
    nodes: list[str],
    edges: pd.DataFrame,
    communities: np.ndarray,
    comm_palette: np.ndarray,
    coords: np.ndarray,
    corum_lookup: dict[frozenset, list[str]],
    max_edges: int,
) -> tuple[pd.DataFrame, np.ndarray, np.ndarray, np.ndarray, list[str]]:
    """Assemble Lines attributes, duplicated across both views.

    Intra-community edges get the community's color (saturated); cross-
    community edges get dim gray. Width is slightly heavier for intra-
    community edges so the modular structure reads clearly.

    Returns:
        final_edges, vertices (4E, 4), widths (4E,), colors (4E, 3),
        labels (4E,)
    """
    idx = {s: i for i, s in enumerate(nodes)}
    a_idx = np.fromiter((idx[s] for s in edges["sym_a"]), dtype=np.int32)
    b_idx = np.fromiter((idx[s] for s in edges["sym_b"]), dtype=np.int32)
    same = communities[a_idx] == communities[b_idx]

    # Subsample if too many edges; keep intra-community preferentially
    if len(edges) > max_edges:
        with asection("Subsampling edges (cap preserves intra-community)"):
            n_same = int(same.sum())
            n_cross = int(len(edges) - n_same)
            rng = np.random.default_rng(42)

            if n_same > max_edges:
                same_positions = np.nonzero(same)[0]
                chosen_same = rng.choice(same_positions, size=max_edges, replace=False)
                keep = np.zeros(len(edges), dtype=bool)
                keep[chosen_same] = True
            else:
                target_cross = max_edges - n_same
                cross_positions = np.nonzero(~same)[0]
                chosen_cross = rng.choice(
                    cross_positions,
                    size=min(target_cross, n_cross),
                    replace=False,
                )
                keep = same.copy()
                keep[chosen_cross] = True

            edges = edges.loc[keep].reset_index(drop=True)
            a_idx = np.fromiter((idx[s] for s in edges["sym_a"]), dtype=np.int32)
            b_idx = np.fromiter((idx[s] for s in edges["sym_b"]), dtype=np.int32)
            same = communities[a_idx] == communities[b_idx]
            aprint(
                f"  Kept {len(edges):,} edges: "
                f"{int(same.sum()):,} intra-community + "
                f"{int((~same).sum()):,} cross-community"
            )

    n_edges = len(edges)
    xs, ys, zs = coords[:, 0], coords[:, 1], coords[:, 2]

    # Vertices per view: (n_edges × 2, 3) flat
    verts_xyz = np.empty((n_edges, 2, 3), dtype=np.float32)
    verts_xyz[:, 0, 0] = xs[a_idx]
    verts_xyz[:, 0, 1] = ys[a_idx]
    verts_xyz[:, 0, 2] = zs[a_idx]
    verts_xyz[:, 1, 0] = xs[b_idx]
    verts_xyz[:, 1, 1] = ys[b_idx]
    verts_xyz[:, 1, 2] = zs[b_idx]
    flat_xyz = verts_xyz.reshape(n_edges * 2, 3)

    view0_col = np.zeros((n_edges * 2, 1), dtype=np.float32)
    view1_col = np.ones((n_edges * 2, 1), dtype=np.float32)
    verts_v0 = np.hstack([view0_col, flat_xyz])
    verts_v1 = np.hstack([view1_col, flat_xyz])
    vertices = np.vstack([verts_v0, verts_v1])

    # Widths (same at both endpoints — interactions are symmetric)
    width_per_edge = np.where(same, 0.015, 0.009).astype(np.float32)
    width_per_vertex_1view = np.repeat(width_per_edge, 2)
    widths = np.concatenate([width_per_vertex_1view, width_per_vertex_1view])

    # Colors
    same_rgb = comm_palette[communities[a_idx]]
    cross_rgb = np.tile(np.array(CROSS_COMMUNITY_COLOR, dtype=np.float32), (n_edges, 1))
    rgb_per_edge = np.where(same[:, None], same_rgb, cross_rgb).astype(np.float32)
    rgb_per_vertex_1view = np.repeat(rgb_per_edge, 2, axis=0)
    colors = np.vstack([rgb_per_vertex_1view, rgb_per_vertex_1view])

    # Labels — with optional CORUM shared-complex line
    labels_per_edge: list[str] = []
    syms_a = edges["sym_a"].tolist()
    syms_b = edges["sym_b"].tolist()
    for i in range(n_edges):
        sa, sb = syms_a[i], syms_b[i]
        pieces = [f"{sa} ⇄ {sb}"]
        if same[i]:
            pieces.append(f"[intra-community #{int(communities[a_idx[i]])}]")
        else:
            pieces.append("[cross-community bridge]")
        shared = corum_lookup.get(frozenset({sa, sb}))
        if shared:
            names = list(dict.fromkeys(shared))  # dedupe, preserve order
            shown = names[:2]
            suffix = f" (+{len(names) - 2} more)" if len(names) > 2 else ""
            pieces.append("Shared complex: " + "; ".join(shown) + suffix)
        labels_per_edge.append("\n".join(pieces))

    labels_per_vertex_1view: list[str] = []
    for lab in labels_per_edge:
        labels_per_vertex_1view.extend([lab, lab])
    labels = labels_per_vertex_1view * 2  # both views share the same labels

    return edges, vertices, widths, colors, labels


