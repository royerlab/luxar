def build_scene(
    output_path: Path,
    nodes: list[str],
    node_df: pd.DataFrame,
    edges: pd.DataFrame,
    coords: np.ndarray,
    communities: np.ndarray,
    degrees: np.ndarray,
    corum_lookup: dict[frozenset, list[str]],
    max_edges: int,
) -> tuple[int, int, int]:
    """Write the Luxar zarr scene. Returns (n_nodes, n_edges_kept, n_communities)."""
    (
        node_positions,
        node_colors,
        node_radii,
        node_labels,
        chrom_cats,
        chrom_codes,
        comm_palette,
        _chrom_palette,
    ) = build_node_points(nodes, node_df, coords, communities, degrees)

    edges_kept, verts, widths, edge_colors, edge_labels = build_edge_lines(
        nodes,
        edges,
        communities,
        comm_palette,
        coords,
        corum_lookup,
        max_edges=max_edges,
    )

    n_nodes = len(nodes)
    n_edges_kept = len(edges_kept)
    n_comms = int(communities.max()) + 1

    corum_hits_kept = (
        sum(
            1
            for sa, sb in zip(edges_kept["sym_a"], edges_kept["sym_b"], strict=True)
            if frozenset({sa, sb}) in corum_lookup
        )
        if corum_lookup
        else 0
    )

    with asection("Building Luxar scene"):
        dims = Dimensions(
            [
                Dimension(
                    "view",
                    unit="",
                    categories=["Community", "Chromosome"],
                    display=False,
                    description=("Color coding (press '1' then '[' / ']' to switch)"),
                ),
                Dimension("x", unit="UMAP", display=True),
                Dimension("y", unit="UMAP", display=True),
                Dimension("z", unit="UMAP", display=True),
            ]
        )

        with LuxarZarrCompiler(output_path) as compiler:
            scene = compiler.create_scene(dimensions=dims)

            scene.add_points(
                "Proteins",
                positions=node_positions,
                colors=node_colors,
                radii=node_radii,
                sharpness=np.full(len(node_positions), 0.55, dtype=np.float32),
                opacity=0.95,
                intensity=0.2,
                labels=node_labels,
                layer=True,
            )

            if len(verts) > 0:
                scene.add_lines(
                    "Interactions",
                    vertices=verts,
                    widths=widths,
                    colors=edge_colors,
                    sharpness=np.full(len(verts), 0.85, dtype=np.float32),
                    line_type="segments",
                    blending_mode="luminous",
                    opacity=0.40,
                    intensity=0.5,
                    labels=edge_labels,
                    layer=True,
                )

            # Title
            scene.add_text(
                "HuRI — Human Reference Interactome",
                position=(0.02, 0.02),
                font_size=0.05,
                anchor="top-left",
                color="rgba(255,255,255,0.65)",
                blend_mode="difference",
            )

            # Hover overlay (center-left avoids clipping the right-side legend)
            scene.add_text(
                "{hover_label}",
                position=(0.02, 0.5),
                anchor="center-left",
                font_size=0.022,
                color="white",
                background="rgba(0,0,0,0.72)",
                padding=0.01,
                text_align="left",
                opacity=1.0,
                transition="fade",
                transition_duration=0.15,
                hover=True,
            )

            # Per-view captions + legends
            community_legend = _build_community_legend(communities)
            chrom_legend = build_legend_html("chromosome", chrom_cats, chrom_codes)

            for view_id, caption, legend_html in [
                (0, "Colored by: Community (Louvain)", community_legend),
                (1, "Colored by: Chromosome (HGNC)", chrom_legend),
            ]:
                scene.add_text(
                    caption,
                    position=(0.02, 0.97),
                    font_size=0.015,
                    anchor="bottom-left",
                    color="#ffcc44",
                    visible_range={"view": view_id},
                    transition="fade",
                    transition_duration=0.2,
                )
                if legend_html:
                    scene.add_html(
                        legend_html,
                        position=(0.98, 0.5),
                        anchor="center-right",
                        opacity=0.92,
                        visible_range={"view": view_id},
                        transition="fade",
                        transition_duration=0.2,
                    )

            # Footer
            footer = [
                f"{n_nodes:,} proteins",
                f"{n_edges_kept:,} interactions",
                f"{n_comms} communities",
            ]
            if corum_hits_kept:
                footer.append(f"{corum_hits_kept:,} CORUM-backed edges")
            footer.append("Luck et al., Nature 2020")
            scene.add_text(
                " · ".join(footer),
                position=(0.98, 0.97),
                font_size=0.012,
                anchor="bottom-right",
                color="rgba(200,200,200,0.5)",
            )

        aprint(
            f"  ✓ Scene: {n_nodes:,} nodes, {n_edges_kept:,} edges, "
            f"{n_comms} communities"
        )

    return n_nodes, n_edges_kept, n_comms


